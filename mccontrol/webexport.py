def _topic(name):
    path = helptext.HERE / f"{name}.txt"
    raw = path.read_text(encoding="utf-8").rstrip("\n").split("\n")
    body = raw[2:] if len(raw) > 1 and raw[1] == "" else raw[1:]
    return {"title": raw[0], "body": "\n".join(body)}


# -- vectors ---------------------------------------------------------------------------------

def _node_key():
    return envelope.public_key_hex(TEST_NODE_SEED)


def _sign_node(topic, line):
    from Crypto.Signature import eddsa
    sig = eddsa.new(envelope.key_from_seed(TEST_NODE_SEED), "rfc8032").sign(envelope.signed_message(topic, line))
    return sig.hex().upper()


def _r3(command_topic, counter, code, command, reply):
    plain = envelope.pad(f"{code}|{command}|{reply}".encode("utf-8"), R3_PADS)
    key = envelope.v2_key(TEST_SEED, _node_key(), command_topic)
    sealed = envelope.seal(key, envelope.DIR_RESULT, counter, f"r3|{counter}".encode("ascii"), plain)
    return f"r3|{counter}|{envelope._b64(sealed)}"


def _result_dict(r):
    if r is None:
        return None
    return {"counter": r.counter, "code": r.code, "command": r.command, "reply": r.reply, "verified": r.verified}


