def _topic_for(leaf):
    node = _node_key()
    if leaf == "all":
        return envelope.command_topic("JKG")
    if leaf == "id":
        return envelope.command_topic("JKG", node[:8])
    return envelope.command_topic("JKG", node[:8], node)


def vectors():
    seed, node = TEST_SEED, _node_key()
    out = {
        "_source": _source("mccontrol/envelope.py", "mccontrol/token.py", "mccontrol/denylist.py",
                           "mccontrol/firmware.py", "mccontrol/actions.py", "mccontrol/facts.py",
                           "mccontrol/commands.py", "mccontrol/mesh.py"),
        "_note": "seeds are SHA-256 of fixed phrases (see webexport.py); never a real key",
        "seed": seed,
        "public_key": envelope.public_key_hex(seed),
        "node_seed": TEST_NODE_SEED,
        "node_key": node,
        "now": TEST_NOW,
    }

    out["topics"] = [
        {"iata": "jkg", "node": node[:8], "key": None,
         "command": envelope.command_topic("jkg", node[:8]), "result": envelope.result_topic("jkg", node[:8])},
        {"iata": "JKG", "node": node[:8], "key": node,
         "command": envelope.command_topic("JKG", node[:8], node), "result": envelope.result_topic("JKG", node[:8], node)},
        {"iata": "VGR", "node": None, "key": None, "command": envelope.command_topic("VGR"), "result": None},
    ]

    v1 = []
    for leaf, counter, ttl, command in V1_CASES:
        topic = _topic_for(leaf)
        part = envelope.signed_part(counter, TEST_NOW + ttl, command)
        v1.append({"topic": topic, "counter": counter, "now": TEST_NOW, "ttl": ttl, "command": command,
                   "signed": envelope.signed_message(topic, part).decode("utf-8"),
                   "payload": envelope.build(seed, topic, counter, command, ttl_secs=ttl, now=TEST_NOW)})
    out["v1"] = v1
    out["v1_errors"] = [{"command": c, "error": True} for c in BAD_COMMANDS] + [
        {"command": "ver", "counter": 4294967296, "error": True},
        {"command": "ver", "ttl": 0, "error": True},
        {"command": "ver", "ttl": 3601, "error": True},
    ]
    for case in out["v1_errors"]:
        try:
            envelope.build(seed, _topic_for("key"), case.get("counter", 1), case["command"],
                           ttl_secs=case.get("ttl", 300), now=TEST_NOW)
            raise AssertionError(f"{case} should have failed")
        except envelope.EnvelopeError:
            pass

    topic = _topic_for("key")
    shared = envelope.shared_secret(seed, node)
    key = envelope.v2_key(seed, node, topic)
    out["v2_keys"] = {
        "topic": topic,
        "x25519_scalar": hashlib.sha512(bytes.fromhex(seed)).digest()[:32].hex(),
        "node_montgomery_u": envelope.montgomery_u(bytes.fromhex(node)).hex(),
        "shared_secret": shared.hex(),
        "shared_secret_from_node_side": envelope.shared_secret(TEST_NODE_SEED, envelope.public_key_hex(seed)).hex(),
        "key": key.hex(),
    }
    out["v2"] = [{"topic": topic, "counter": c, "now": TEST_NOW, "ttl": ttl, "command": cmd, "node_key": node,
                  "nonce": envelope.v2_nonce(envelope.DIR_COMMAND, c).hex(),
                  "payload": envelope.build_v2(seed, topic, c, cmd, node, ttl_secs=ttl, now=TEST_NOW)}
                 for c, ttl, cmd in V2_CASES]

    rtopic = envelope.result_topic("JKG", node[:8], node)
    results = []

    def r(kind, payload, **kw):
        if kind == "r3":
            parsed = envelope.parse_r3(payload, node[:8], seed, node, topic)
        else:
            parsed = envelope.parse_result(payload, node[:8], **kw)
        results.append({"kind": kind, "payload": payload, "topic": rtopic,
                        "with_key": bool(kw.get("key_hex")) or kind == "r3", "result": _result_dict(parsed)})

    r("r1", "r1|1794800000|0|ver|> esp32s3-v1.17.1-lou-18-arrc-observer-1a2b3c4d")
    r("r1", "r1|5|14|set prv.key x|")
    r("r1", "r1|6|0|get name|> a|b|c")
    r("r1", "r1|x|0|ver|")
    r("r1", "r1|1|0|ver")
    r("r1", "r9|1|0|ver|x")
    line = "r2|1794800001|0|get name|> SE-JKG-Test"
    r2 = f"{line}|{_sign_node(rtopic, line)}"
    r("r2", r2, topic=rtopic, key_hex=node)
    r("r2", r2)                                                    # no key: unverified, not refused
    r("r2", r2.replace("SE-JKG-Test", "SE-JKG-Evil"), topic=rtopic, key_hex=node)
    refused = f"r2|{TEST_NOW + 4}|9||"                             # a refused v2 (lou-19): no command
    r("r2", f"{refused}|{_sign_node(rtopic, refused)}", topic=rtopic, key_hex=node)
    r("r3", _r3(topic, TEST_NOW, 0, "ver", "> esp32s3-v1.17.1-lou-18-arrc-observer-1a2b3c4d"))
    r("r3", _r3(topic, TEST_NOW + 1, 14, "set prv.key x", ""))
    r("r3", _r3(topic, TEST_NOW + 2, 0, "neighbors", "> " + "AABBCCDD:-5:10," * 20))      # second pad
    sealed = _r3(topic, TEST_NOW + 3, 0, "ver", "> ok")
    r("r3", sealed[:-2] + ("A" if sealed[-2] != "A" else "B") + sealed[-1])            # tag broken: forged
    r("r3", "r3|12|!!!")
    out["results"] = results

    out["token"] = {"audience": AUDIENCE, "now": TEST_NOW, "lifetime": token.LIFETIME_SECS,
                    "username": token.username(seed), "password": token.make(seed, AUDIENCE, now=TEST_NOW)}
    out["registration"] = {"now": TEST_NOW, "topic": envelope.REGISTER_TOPIC,
                           "ack_topic": envelope.register_ack_topic(envelope.public_key_hex(seed)),
                           "payload": envelope.register_payload(seed, now=TEST_NOW)}
    out["checks"] = _checks()
    out["mesh"] = _mesh_vectors()
    return out


